import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";

test("project foundation preserves legacy rows and binds new projects, sales contracts and products to one tenant", () => {
  const schema = readFileSync("prisma/schema.prisma", "utf8");
  const migration = readFileSync("prisma/migrations/202611170001_project_foundation/migration.sql", "utf8");
  assert.match(schema, /model Project {[\s\S]*tenant_id\s+String\?[\s\S]*customer_master_id\s+String\?[\s\S]*@@unique\(\[id, tenant_id\]\)/);
  assert.match(schema, /model Contract {[\s\S]*tenant_id\s+String\?[\s\S]*counterparty_customer_id\s+String\?/);
  assert.match(schema, /model ContractVersion {[\s\S]*tenant_id\s+String\?/);
  assert.match(schema, /model ProjectAuditEvent/);
  assert.match(migration, /CREATE TABLE "LegacyProjectQuarantine"/);
  assert.match(migration, /CREATE TABLE "LegacyContractQuarantine"/);
  assert.match(migration, /Project_customer_tenant_fkey/);
  assert.match(migration, /Contract_customer_tenant_fkey/);
  assert.match(migration, /Contract_project_customer_tenant_fkey/);
  assert.match(migration, /Project_primary_sales_contract_project_fkey/);
  assert.match(migration, /ContractVersion_contract_tenant_fkey/);
  assert.match(migration, /Contract_active_version_contract_fkey/);
  assert.match(schema, /fields: \[active_version_id, id\], references: \[id, contract_id\]/);
  assert.match(migration, /CREATE CONSTRAINT TRIGGER "ContractVersion_validate_tenant"[\s\S]*DEFERRABLE INITIALLY DEFERRED/);
  assert.match(migration, /product_tenant IS DISTINCT FROM parent_tenant/);
  assert.match(migration, /IF parent_tenant IS NULL THEN[\s\S]*RETURN NEW/);
  assert.match(migration, /ADD CONSTRAINT "fk_9_ContractVersion"/);
  assert.match(migration, /orb_guard_immutable_content\('state', 'approval_id', 'tenant_id'\)/);
  assert.match(migration, /ContractVersion_product_tenant_fkey/);
  assert.match(migration, /Contract_validate_project_tenant/);
  assert.match(migration, /Project_validate_primary_sales_contract/);
  assert.match(migration, /CREATE CONSTRAINT TRIGGER "Project_validate_primary_sales_contract"[\s\S]*DEFERRABLE INITIALLY DEFERRED/);
  assert.match(migration, /contract version tenant mismatch/);
  for (const table of ["AuditEvent", "Claim", "ClosureAssessment", "CommercialDocument", "Contract", "DirectExpense", "EvidenceLink", "EvidenceObject", "MoneyMovement", "ProfitSnapshot", "SalesInvoice", "SalesShipment", "SupplierInvoice", "SupplierShipment", "TransactionSerial"]) assert.match(migration, new RegExp(`FROM "${table}"`));
  assert.match(schema, /ContractVersion {[\s\S]*CoffeeSpecification\s+CoffeeSpecification\s+@relation\(fields: \[coffee_specification_id\]/);
  assert.doesNotMatch(migration, /UNIQUE INDEX "Contract_project_id_tenant_id/);
  assert.match(migration, /ProjectAuditEvent_append_only/);
  assert.match(migration, /Project_tenant_shape/);
  assert.match(migration, /Contract_tenant_shape/);
  assert.doesNotMatch(migration, /UPDATE "Project" SET "tenant_id"/);
  assert.doesNotMatch(migration, /UPDATE "Contract" SET "tenant_id"/);
});
