export type ClosureBlockerCode = typeof CLOSURE_BLOCKER_CODES[keyof typeof CLOSURE_BLOCKER_CODES];

const ELIGIBLE = new Set<ClosureBlockerCode>([
  CLOSURE_BLOCKER_CODES.SALES_SHIPMENT_NOT_DELIVERED,
  CLOSURE_BLOCKER_CODES.SUPPLIER_SHIPMENT_NOT_RECEIVED,
  CLOSURE_BLOCKER_CODES.SUPPLIER_INVOICE_MISSING,
  CLOSURE_BLOCKER_CODES.ROUTE_ITEM_INCOMPLETE,
  CLOSURE_BLOCKER_CODES.CINV_MISSING,
  CLOSURE_BLOCKER_CODES.PACKING_LIST_MISSING,
  CLOSURE_BLOCKER_CODES.EXPENSE_INCOMPLETE,
  CLOSURE_BLOCKER_CODES.CLAIM_INCOMPLETE,
]);

export function isClosureExceptionEligible(code: ClosureBlockerCode): boolean {
  return ELIGIBLE.has(code);
}
