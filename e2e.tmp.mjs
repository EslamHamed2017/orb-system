import { chromium } from "@playwright/test";
import { readFileSync } from "node:fs";
const trade = JSON.parse(readFileSync("/tmp/e2e/trade.json", "utf8"));
const creds = JSON.parse(readFileSync("/tmp/e2e/creds.json", "utf8"));
const base = "http://localhost:3100";
const browser = await chromium.launch();
const as = async (who) => {
  const ctx = await browser.newContext({ baseURL: base, viewport: { width: 1280, height: 900 } });
  const page = await ctx.newPage(); page.on("pageerror", (e) => console.log("PAGEERROR", e.message));
  const r = await page.request.post("/api/sessions", { data: { login: creds.logins[who], credential: creds.password }, headers: { origin: base, "idempotency-key": crypto.randomUUID() } });
  if (!r.ok()) throw new Error(`sign in ${who}: ${r.status()} ${await r.text()}`);
  return page;
};
const step = (s) => console.log("✓", s);
let p = await as("finance");
await p.goto(`/supplier-shipments/${trade.supplierShipment}?locale=en`);
const panel = p.getByTestId("shipment-invoices");
await panel.getByRole("button", { name: "Record supplier invoice" }).click();
await panel.getByLabel("Supplier invoice number").fill("AD-2026-0777");
await panel.getByLabel("Amount on the invoice").fill("99900");
await panel.getByLabel(/Invoice document/).setInputFiles("/tmp/e2e/pdf.pdf");
await panel.getByRole("button", { name: "Save invoice" }).click();
await panel.getByText("Supplier invoice saved").waitFor();
await panel.getByText("Expected USD 99,849.60 from the contract").waitFor();
step("finance saved invoice; difference vs contract shown");
const docResp = await p.request.get(await panel.getByRole("link", { name: "View document" }).getAttribute("href"));
step(`document download ${docResp.status()} ${docResp.headers()["content-type"]} ${(await docResp.body()).subarray(0,5)}`);
await panel.getByRole("button", { name: "Submit for approval" }).click();
await panel.getByText("Waiting for approval").waitFor(); step("submitted");
await p.screenshot({ path: "/tmp/e2e/1-finance.png", fullPage: true });
p = await as("owner");
await p.goto(`/approvals?locale=en`);
const card = p.locator("article", { hasText: "AD-2026-0777" });
await card.getByText("differs from contract").waitFor();
await p.screenshot({ path: "/tmp/e2e/2-inbox.png", fullPage: true });
await card.getByRole("button", { name: /Approve/ }).click();
await p.getByText("AD-2026-0777 approved").waitFor(); step("owner approved in inbox");
await p.goto(`/supplier-shipments/${trade.supplierShipment}?locale=en`);
await p.getByTestId("shipment-invoices").getByText("Approved").waitFor(); step("shipment shows Approved");
p = await as("finance");
